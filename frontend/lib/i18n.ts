// Real photo covers live in /public/covers as JPEG files. Seed data stores a
// direct `/covers/*.jpg` path; the legacy `.svg` placeholder names are kept as a
// fallback so older demo databases keep working after the asset migration.
const legacyCovers: Record<string, string> = {
  portrait: '/covers/portrait.jpg',
  city: '/covers/city.jpg',
  nature: '/covers/nature.jpg',
  warm: '/covers/warm.jpg',
  duo: '/covers/duo.jpg',
  mountain: '/covers/mountain.jpg',
};

export function templateCover(url: string): string {
  const match = url.match(/^\/covers\/(portrait|city|nature|warm|duo|mountain)\.(svg|png)$/);
  return match ? legacyCovers[match[1]] : url;
}
